/**
 * Injected randomness. Game setup takes an Rng so tests (and the
 * hotseat-vs-LAN equivalence check) can reproduce a shuffle exactly.
 * The LAN server seeds from crypto and never sends the seed to clients.
 */
export type Rng = () => number; // uniform in [0, 1)

/** Small deterministic PRNG (mulberry32). Not cryptographic; fine for shuffling a prototype deck. */
export function seededRng(seed: number): Rng {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Fisher–Yates shuffle returning a new array. */
export function shuffled<T>(items: readonly T[], rng: Rng): T[] {
  const out = items.slice();
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    const tmp = out[i]!;
    out[i] = out[j]!;
    out[j] = tmp;
  }
  return out;
}
